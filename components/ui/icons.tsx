/** Round tinted badge holding an icon, for page-level status messages */
export function IconBadge({
  children,
  tone = "coral",
  className = "h-16 w-16",
}: {
  children: ReactNode;
  tone?: "coral" | "green";
  className?: string;
}) {
  return (
    <span
      className={`mx-auto flex items-center justify-center rounded-full ${tone === "green" ? "bg-green-100 text-green-700" : "bg-coral/10 text-coral"} ${className}`}
    >
      {children}
    </span>
  );
}
